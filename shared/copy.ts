type Groups = typeof COPY_GROUPS;
type KeysOf<G> = G extends { items: infer T } ? keyof T : never;
export type CopyKey = KeysOf<Groups[number]> & string;

export const COPY_DEFS: Record<CopyKey, CopyDef> = Object.assign({}, ...COPY_GROUPS.map((g) => g.items));
export const COPY_KEYS = Object.keys(COPY_DEFS) as CopyKey[];

/** Текст для сайта: изменённый в админке или стандартный */
export function copyText(overrides: Partial<Record<string, string>> | undefined, key: CopyKey): string {
  const def = COPY_DEFS[key];
  const v = overrides?.[key];
  if (v === undefined) return def.def;
  if (v.trim() === '' && !def.optional) return def.def;
  return v;
}
